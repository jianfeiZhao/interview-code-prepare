"""
LeetCode #71 - 简化路径 (Simplify Path)
难度: Medium | 频率: 字节/阿里

=== 题目描述 ===
给你一个字符串 path，表示指向某一文件或目录的 Unix 风格绝对路径（以 '/' 开头），
请你将其转化为更加简洁的规范路径。
在 Unix 风格的文件系统中，一个点（.）表示当前目录本身；
两个点（..）表示将目录切换到上一级目录（父目录），不能超过根目录；
任意多个连续的斜杠（即，'//'）都被视为单个斜杠 '/'。

规范路径要求：
  - 以单斜杠 '/' 开始
  - 两个目录名之间只有一个斜杠 '/'
  - 路径不能以 '/' 结尾（根目录除外）
  - 不含任何 '.' 或 '..'

示例 1: "/home/"         -> "/home"
示例 2: "/../"           -> "/"（不能超过根目录）
示例 3: "/home//foo/"    -> "/home/foo"
示例 4: "/a/./b/../../c/" -> "/c"

=== TL;DR ===
核心思路: 按 '/' 分割路径，用栈处理每个部分：
  - '..'  -> 弹出栈顶（返回上级目录），栈为空时不操作
  - '.'   -> 跳过（当前目录）
  - ''    -> 跳过（多余斜杠产生）
  - 其他  -> 入栈（目录名）
  最后将栈中内容用 '/' 拼接并加上前导 '/'

时间复杂度: O(n)
空间复杂度: O(n)

=== 详细解析 ===
关键技巧:
1. path.split('/') 会产生空字符串（处理开头'/'和多余'///'）
2. 只需要关注 '..' 和其他非空非'.'的部分，其余都跳过
3. '..' 时栈不为空才弹出（不能超出根目录）
4. 结果: '/' + '/'.join(stack)，若 stack 为空则返回 '/'
"""


# ===== 标准栈解法 =====
def simplify_path(path: str) -> str:
    stack = []
    for part in path.split('/'):
        if part == '..':
            if stack:
                stack.pop()     # 返回上级目录
        elif part and part != '.':
            stack.append(part)  # 有效目录名入栈
        # '' 和 '.' 直接跳过
    return '/' + '/'.join(stack)


# ===== 测试 =====
if __name__ == "__main__":
    cases = [
        ("/home/", "/home"),
        ("/../", "/"),
        ("/home//foo/", "/home/foo"),
        ("/a/./b/../../c/", "/c"),
        ("/", "/"),
        ("/a//b////c/d//././/..", "/a/b/c"),
        ("/a/../../b/../c//.//", "/c"),
        ("/a/b/c", "/a/b/c"),
        ("/..hidden", "/..hidden"),  # ..hidden 是目录名，不是 ..
        ("/..", "/"),
        ("/a/b/../../..", "/"),     # 多次返回上级，超出根目录停在根
        ("/a/./.", "/a"),
        ("//", "/"),
        ("///", "/"),
    ]
    for path, expected in cases:
        result = simplify_path(path)
        assert result == expected, \
            f"simplify_path({path!r}) = {result!r}, expected {expected!r}"

    print("All tests passed!")
